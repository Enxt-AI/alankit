  async validateVoucherDate(date: Date | string) {
    const checkTime = new Date(date).getTime();
    if (isNaN(checkTime)) return;

    // We strip the hours/minutes/seconds to do strict calendar date comparisons
    const checkDateOnly = new Date(date);
    checkDateOnly.setHours(0, 0, 0, 0);
    const checkDateTime = checkDateOnly.getTime();

    const periods = await this.prisma.accountingPeriod.findMany({
      where: { isActive: true },
    });

    for (const period of periods) {
      if (period.lockStartDate && period.lockEndDate) {
        const lockStart = new Date(period.lockStartDate);
        lockStart.setHours(0, 0, 0, 0);
        const lockStartVal = lockStart.getTime();

        const lockEnd = new Date(period.lockEndDate);
        lockEnd.setHours(23, 59, 59, 999);
        const lockEndVal = lockEnd.getTime();

        if (checkDateTime >= lockStartVal && checkDateTime <= lockEndVal) {
          const fmtDate = (dInput: any) => {
            const d = new Date(dInput);
            return `${String(d.getDate()).padStart(2, '0')}/${String(d.getMonth() + 1).padStart(2, '0')}/${d.getFullYear()}`;
          };
          throw new BadRequestException(
            `Voucher operation rejected. The transaction date (${fmtDate(date)}) falls within the locked accounting period "${period.name}" (${fmtDate(period.lockStartDate)} to ${fmtDate(period.lockEndDate)}) set by the administrator.`,
          );
        }
      }
    }
  }

