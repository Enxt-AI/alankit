  async updateLedger(id: string, dto: UpdateLedgerDto) {
    const existing = await this.prisma.ledger.findUnique({ where: { id } });
    if (!existing) {
      throw new NotFoundException('Ledger not found');
    }

    if (existing.stockId) {
      const currentStock = await this.prisma.stock.findUnique({
        where: { id: existing.stockId },
      });
      if (currentStock) {
        const newQty = dto.openingQuantity !== undefined ? dto.openingQuantity : currentStock.openingQuantity;
        const newRate = dto.openingRate !== undefined ? dto.openingRate : currentStock.openingRate;
        const newValue = newQty * newRate;

        const shouldUpdateStockQuantity = currentStock.stockQuantity === 0;

        await this.prisma.stock.update({
          where: { id: existing.stockId },
          data: {
            openingQuantity: newQty,
            openingRate: newRate,
            openingValue: newValue,
            ...(shouldUpdateStockQuantity && { stockQuantity: newQty }),
          },
        });

        if (dto.openingQuantity !== undefined || dto.openingRate !== undefined) {
          dto.openingBalance = newValue;
          dto.openingBalanceType = 'DR';
        }
      }
    }

    let updatedType: LedgerType | undefined;
    if (dto.groupId !== undefined) {
      if (dto.groupId) {
        const group = await this.prisma.accountingGroup.findUnique({
          where: { id: dto.groupId },
        });
        if (group) {
          if (group.under === 'Bank Accounts') {
            updatedType = 'BANK';
          } else if (
            group.under === 'Sales Accounts' ||
            group.under === 'Direct Income' ||
            group.under === 'Indirect Income'
          ) {
            updatedType = 'SALE';
          } else if (group.under === 'Purchase Accounts') {
            updatedType = 'PURCHASE';
          } else if (
            group.name === 'Stock-in-hand' ||
            group.under === 'Stock-in-hand' ||
            group.name === 'Stock Accounts' ||
            group.under === 'Stock Accounts' ||
            group.name === 'Stock' ||
            group.under === 'Stock' ||
            group.name === 'Stocks' ||
            group.under === 'Stocks'
          ) {
            updatedType = 'STOCK';
          } else {
            updatedType = 'USER';
          }
        }
      }
    }

    let updatedCode = dto.code;
    if (updatedCode !== undefined) {
      if (updatedCode) {
        updatedCode = updatedCode.trim().toUpperCase();
        if (updatedCode.length !== 6) {
          throw new BadRequestException('Ledger code must be exactly 6 characters');
        }
        const existingCode = await this.prisma.ledger.findFirst({
          where: { code: updatedCode, id: { not: id } },
        });
        if (existingCode) {
          throw new BadRequestException(`Ledger code "${updatedCode}" already exists`);
        }
      }
    }

    const oldSignedOp = existing.openingBalance * (existing.openingBalanceType === 'CR' ? -1 : 1);
    const newOpVal = dto.openingBalance !== undefined ? dto.openingBalance : existing.openingBalance;
    const newOpType = dto.openingBalanceType !== undefined ? dto.openingBalanceType : existing.openingBalanceType;
    const newSignedOp = newOpVal * (newOpType === 'CR' ? -1 : 1);
    const balanceDiff = newSignedOp - oldSignedOp;

    const ledger = await this.prisma.ledger.update({
      where: { id },
      data: {
        ...(dto.name !== undefined && { name: dto.name }),
        ...(dto.openingBalance !== undefined && {
          openingBalance: dto.openingBalance,
        }),
        ...(dto.openingBalanceType !== undefined && {
          openingBalanceType: dto.openingBalanceType,
        }),
        ...(balanceDiff !== 0 && {
          currentBalance: { increment: balanceDiff },
        }),
        ...(updatedCode !== undefined && { code: updatedCode }),
        ...(dto.bankName !== undefined && { bankName: dto.bankName }),
        ...(dto.accountNumber !== undefined && {
          accountNumber: dto.accountNumber,
        }),
        ...(dto.ifscCode !== undefined && { ifscCode: dto.ifscCode }),
        ...(dto.phone !== undefined && { phone: dto.phone }),
        ...(dto.email !== undefined && { email: dto.email }),
        ...(dto.pan !== undefined && { pan: dto.pan }),
        ...(dto.gstNo !== undefined && { gstNo: dto.gstNo }),
        ...(dto.tanNo !== undefined && { tanNo: dto.tanNo }),
        ...(dto.dematAccountNo !== undefined && { dematAccountNo: dto.dematAccountNo }),
        ...(dto.clientBankAccountNo !== undefined && { clientBankAccountNo: dto.clientBankAccountNo }),
        ...(dto.clientIfscCode !== undefined && { clientIfscCode: dto.clientIfscCode }),
        ...(dto.address !== undefined && { address: dto.address }),
        ...(dto.isActive !== undefined && { isActive: dto.isActive }),
        ...(dto.sunCode !== undefined && { sunCode: dto.sunCode }),
        ...(dto.sunName !== undefined && { sunName: dto.sunName }),
        ...(dto.groupId !== undefined && { groupId: dto.groupId || null }),
        ...(updatedType !== undefined && { type: updatedType }),
      },
      include: {
        group: true,
        stock: true,
      },
    });

    return { success: true, ledger };
  }

