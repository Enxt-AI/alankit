  async rolloverAccountingPeriod(id: string) {
    const period = await this.prisma.accountingPeriod.findUnique({
      where: { id },
    });
    if (!period) {
      throw new NotFoundException('Accounting period not found');
    }

    const incrementYearVal = (dInput: any) => {
      if (!dInput) return null;
      const d = new Date(dInput);
      d.setFullYear(d.getFullYear() + 1);
      return d;
    };

    const nameMatch = period.name.match(/FY\s*(\d{4})-(\d{2})/i);
    let newName = period.name;
    if (nameMatch) {
      const startYear = parseInt(nameMatch[1], 10);
      const endYear = parseInt(nameMatch[2], 10);
      newName = `FY ${startYear + 1}-${String(endYear + 1).padStart(2, '0')}`;
    } else {
      newName = `${period.name} (Rolled)`;
    }

    // Set other periods to inactive
    await this.prisma.accountingPeriod.updateMany({
      data: { isActive: false },
    });

    const rolled = await this.prisma.accountingPeriod.create({
      data: {
        name: newName,
        startDate: incrementYearVal(period.startDate)!,
        endDate: incrementYearVal(period.endDate)!,
        lockStartDate: incrementYearVal(period.lockStartDate),
        lockEndDate: incrementYearVal(period.lockEndDate),
        isActive: true,
      },
    });

    return rolled;
  }

