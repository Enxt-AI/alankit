  /**
   * Recalculate currentBalance for ALL active ledgers from their voucher entries.
   * Formula: openingBalance + SUM(DEBIT amounts) - SUM(CREDIT amounts)
   * This corrects any drift caused by bugs in previous voucher generation flows.
   */
  async recalculateAllBalances() {
    const ledgers = await this.prisma.ledger.findMany({
      where: { isActive: true },
      select: { id: true, name: true, openingBalance: true, openingBalanceType: true, currentBalance: true },
    });

    const results: { id: string; name: string; oldBalance: number; newBalance: number }[] = [];

    const hasGroupBy = typeof this.prisma.voucherEntry?.groupBy === 'function';
    const sumsByLedger = new Map<string, { debit: Prisma.Decimal; credit: Prisma.Decimal }>();

    if (hasGroupBy) {
      const grouped = await this.prisma.voucherEntry.groupBy({
        by: ['ledgerId', 'entryType'],
        where: {
          voucher: { status: 'APPROVED' },
        },
        _sum: { amount: true },
      });

      for (const row of grouped) {
        const cur = sumsByLedger.get(row.ledgerId) || {
          debit: new Prisma.Decimal(0),
          credit: new Prisma.Decimal(0),
        };
        const amtDec = new Prisma.Decimal(String(row._sum.amount || 0));
        if (row.entryType === 'DEBIT') {
          cur.debit = cur.debit.plus(amtDec);
        } else if (row.entryType === 'CREDIT') {
          cur.credit = cur.credit.plus(amtDec);
        }
        sumsByLedger.set(row.ledgerId, cur);
      }
    }

    for (const ledger of ledgers) {
      let totalDebitDec: Prisma.Decimal;
      let totalCreditDec: Prisma.Decimal;

      if (hasGroupBy) {
        const sums = sumsByLedger.get(ledger.id);
        totalDebitDec = (sums ? sums.debit : new Prisma.Decimal(0)).toDecimalPlaces(2);
        totalCreditDec = (sums ? sums.credit : new Prisma.Decimal(0)).toDecimalPlaces(2);
      } else {
        const debitSum = await this.prisma.voucherEntry.aggregate({
          where: {
            ledgerId: ledger.id,
            entryType: 'DEBIT',
            voucher: { status: 'APPROVED' },
          },
          _sum: { amount: true },
        });

        const creditSum = await this.prisma.voucherEntry.aggregate({
          where: {
            ledgerId: ledger.id,
            entryType: 'CREDIT',
            voucher: { status: 'APPROVED' },
          },
          _sum: { amount: true },
        });

        totalDebitDec = new Prisma.Decimal(String(debitSum._sum.amount || 0)).toDecimalPlaces(2);
        totalCreditDec = new Prisma.Decimal(String(creditSum._sum.amount || 0)).toDecimalPlaces(2);
      }

      const opSign = ledger.openingBalanceType === 'CR' ? -1 : 1;
      const opDec = new Prisma.Decimal(String(ledger.openingBalance || 0)).mul(opSign).toDecimalPlaces(2);
      const newBalanceDec = opDec.plus(totalDebitDec).minus(totalCreditDec).toDecimalPlaces(2);
      const newBalance = newBalanceDec.toNumber();
      const curBalanceDec = new Prisma.Decimal(String(ledger.currentBalance || 0)).toDecimalPlaces(2);

      if (!newBalanceDec.eq(curBalanceDec)) {
        await this.prisma.ledger.update({
          where: { id: ledger.id },
          data: { currentBalance: newBalance },
        });

        results.push({
          id: ledger.id,
          name: ledger.name,
          oldBalance: ledger.currentBalance,
          newBalance,
        });
      }
    }

    return {
      success: true,
      message: `Recalculated ${results.length} ledger(s) with balance drift`,
      updated: results,
      totalChecked: ledgers.length,
    };
  }

