  async getAllLedgers(type?: string, search?: string, activeOnly = true) {
    const where: any = {};
    if (activeOnly) {
      where.isActive = true;
    }

    // Allow filtering by specific type; without filter return BANK + USER + PURCHASE (exclude system STOCK ledgers by default)
    if (type === 'ALL') {
      // Do not set where.type to return all ledger types (BANK, USER, STOCK, PURCHASE, SALE)
    } else if (type && (['BANK', 'USER', 'STOCK', 'PURCHASE', 'SALE'] as string[]).includes(type)) {
      where.type = type as LedgerType;
    } else if (!type) {
      // Default: return all ledger types that are useful for voucher entry selection
      where.type = { in: ['BANK', 'USER', 'PURCHASE'] as LedgerType[] };
    }

    if (search) {
      const cleanSearch = search.trim();
      const tokens = cleanSearch.split(/\s+/).filter(Boolean);
      where.OR = [
        { name: { contains: cleanSearch, mode: 'insensitive' } },
        ...(tokens.length > 1
          ? [
              {
                AND: tokens.map((token) => ({
                  name: { contains: token, mode: 'insensitive' as const },
                })),
              },
            ]
          : []),
        { code: { contains: cleanSearch, mode: 'insensitive' } },
        { pan: { contains: cleanSearch, mode: 'insensitive' } },
        { dematAccountNo: { contains: cleanSearch, mode: 'insensitive' } },
        { sunCode: { contains: cleanSearch, mode: 'insensitive' } },
        { sunName: { contains: cleanSearch, mode: 'insensitive' } },
      ];
    }

    const ledgers = await this.prisma.ledger.findMany({
      where,
      include: {
        group: true,
        stock: true,
        user: { select: { kycStatus: true } },
      },
      orderBy: { createdAt: 'desc' },
    });

    return { success: true, ledgers, count: ledgers.length };
  }

