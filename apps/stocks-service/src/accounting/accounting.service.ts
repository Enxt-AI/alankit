  /**
   * Generate a unique ledger code of exactly 6 characters.
   * PREFIX: UL (User), BL (Bank), SL (Sale), PL (Purchase), SK (Stock)
   * Example: UL4D88
   */
  private async generateLedgerCode(
    type: 'USER' | 'BANK' | 'SALE' | 'STOCK' | 'PURCHASE',
  ): Promise<string> {
    const prefixMap = { USER: 'UL', BANK: 'BL', SALE: 'SL', STOCK: 'SK', PURCHASE: 'PL' };
    const prefix = prefixMap[type] || 'LD';

    // Retry loop to handle collisions on the 6-character code
    for (let attempt = 0; attempt < 10; attempt++) {
      const uniqueId = crypto
        .randomBytes(2)
        .toString('hex')
        .toUpperCase()
        .slice(0, 4);
      const code = `${prefix}${uniqueId}`;

      const existing = await this.prisma.ledger.findUnique({
        where: { code },
      });
      if (!existing) return code;
    }

    // Fallback with timestamp suffix
    const ts = Date.now().toString(36).toUpperCase().slice(-4);
    return `${prefix}${ts}`;
  }

