  /**
   * Amend (edit) a single VoucherEntry.
   * Editable fields: narration, qty, rate, amount, remarks.
   * When amount changes, the linked ledger's currentBalance is adjusted atomically.
   */
  async amendVoucherEntry(
    entryId: string,
    dto: {
      narration?: string;
      qty?: number;
      rate?: number;
      amount?: number;
      remarks?: string;
      metadata?: any;
    },
  ) {
    const entry = await this.prisma.voucherEntry.findUnique({
      where: { id: entryId },
      include: { ledger: true, voucher: true },
    });

    if (!entry) {
      throw new NotFoundException('Voucher entry not found');
    }

    const amountDelta = dto.amount !== undefined ? dto.amount - entry.amount : 0;

    const updated = await this.prisma.$transaction(async (tx) => {
      const updatedEntry = await tx.voucherEntry.update({
        where: { id: entryId },
        data: {
          ...(dto.narration !== undefined && { narration: dto.narration }),
          ...(dto.qty !== undefined && { qty: dto.qty }),
          ...(dto.rate !== undefined && { rate: dto.rate }),
          ...(dto.amount !== undefined && { amount: dto.amount }),
          ...(dto.remarks !== undefined && { remarks: dto.remarks }),
          ...(dto.metadata !== undefined && { metadata: dto.metadata }),
        },
        include: {
          ledger: { select: { id: true, name: true, type: true } },
          voucher: { select: { id: true, voucherNumber: true, type: true, date: true } },
        },
      });

      // Adjust ledger balance if amount changed
      if (amountDelta !== 0 && entry.ledger) {
        const sign = entry.entryType === 'DEBIT' ? 1 : -1;
        await tx.ledger.update({
          where: { id: entry.ledgerId },
          data: { currentBalance: { increment: sign * amountDelta } },
        });
      }

      return updatedEntry;
    });

    return { success: true, entry: updated };
  }

