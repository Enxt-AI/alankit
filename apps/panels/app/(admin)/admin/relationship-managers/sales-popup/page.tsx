'use client';

import { Suspense, useEffect, useState } from 'react';
import { useSearchParams } from 'next/navigation';
import { Badge } from '@/components/ui/badge';
import { Card, CardContent } from '@/components/ui/card';
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from '@/components/ui/table';
import {
  Users,
  Search,
  Copy,
  CheckCircle2,
  Calendar,
  Ticket,
  DollarSign,
  BarChart3,
  Loader2,
  Sparkles,
} from 'lucide-react';
import { Button } from '@/components/ui/button';

interface Coupon {
  id: string;
  code: string;
  rmId: string;
  minQuantity: number;
  maxQuantity: number;
  discountAmount: number;
  discountType?: string;
  discountPercentage?: number;
  isUsed: boolean;
  usedAt: string | null;
  expiresAt: string | null;
  createdAt: string;
  stock: { name: string; price: number };
  assignedUser?: { fullName: string; email: string } | null;
  usedByUser?: { fullName: string; email: string; phone?: string | null } | null;
  order?: { quantity: number; totalAmount: number; status?: string } | null;
}

interface RMInfo {
  name: string;
  email: string;
}

function RmSalesPopupContent() {
  const searchParams = useSearchParams();
  const rmId = searchParams.get('id');

  const [rmInfo, setRmInfo] = useState<RMInfo | null>(null);
  const [sales, setSales] = useState<Coupon[]>([]);
  const [isLoading, setIsLoading] = useState(true);
  const [salesSearchQuery, setSalesSearchQuery] = useState('');
  const [copiedCode, setCopiedCode] = useState('');

  useEffect(() => {
    if (!rmId) return;

    const fetchData = async () => {
      setIsLoading(true);
      try {
        // 1. Fetch RM's sales coupons
        const salesResponse = await fetch(`/api/stocks/coupons?rmId=${rmId}`, {
          credentials: 'include',
        });
        
        // 2. Fetch all RMs to match current info
        const rmsResponse = await fetch('/api/auth/admin/rms', {
          credentials: 'include',
        });

        if (salesResponse.ok && rmsResponse.ok) {
          const salesData = await salesResponse.json();
          const rmsData = await rmsResponse.json();

          // Match RM details
          const currentRm = rmsData.rms?.find((r: any) => r.id === rmId);
          if (currentRm) {
            setRmInfo({ name: currentRm.name, email: currentRm.email });
          }

          // Filter to only used coupons
          const couponsArray = Array.isArray(salesData) ? salesData : salesData.coupons || [];
          const usedCoupons = couponsArray.filter((c: any) => c.isUsed);
          setSales(usedCoupons);
        }
      } catch (err) {
        console.error('Error fetching RM popup data:', err);
      } finally {
        setIsLoading(false);
      }
    };

    fetchData();
  }, [rmId]);

  // Filter Sales Logs dynamically
  const filteredSales = sales.filter((sale) => {
    const code = sale.code.toLowerCase();
    const stockName = (sale.stock?.name || '').toLowerCase();
    const clientName = (sale.usedByUser?.fullName || '').toLowerCase();
    const clientEmail = (sale.usedByUser?.email || '').toLowerCase();
    const query = salesSearchQuery.toLowerCase();

    return (
      code.includes(query) ||
      stockName.includes(query) ||
      clientName.includes(query) ||
      clientEmail.includes(query)
    );
  });

  // Compute stats dynamically based on filtered logs
  const totalConversions = filteredSales.length;
  const totalRevenueDriven = filteredSales.reduce((sum, s) => sum + (s.order?.totalAmount || 0), 0);
  const totalDiscountDisbursed = filteredSales.reduce((sum, s) => sum + s.discountAmount, 0);

  const copyToClipboard = (text: string) => {
    navigator.clipboard.writeText(text);
    setCopiedCode(text);
    setTimeout(() => setCopiedCode(''), 2000);
  };

  if (isLoading) {
    return (
      <div className="flex h-screen items-center justify-center bg-background">
        <div className="flex flex-col items-center gap-3">
          <Loader2 className="animate-spin h-10 w-10 text-primary" />
          <p className="text-sm font-semibold text-muted-foreground">Loading relationship manager sales data...</p>
        </div>
      </div>
    );
  }

  return (
    <div className="p-6 md:p-8 space-y-6 max-w-7xl mx-auto bg-background min-h-screen">
      {/* Titleblock */}
      <div className="flex flex-col md:flex-row justify-between items-start md:items-center gap-4 border-b pb-4">
        <div className="space-y-1">
          <h1 className="text-2xl font-bold flex items-center gap-2 tracking-tight">
            <Users className="h-6 w-6 text-primary" />
            Sales History: {rmInfo?.name || 'RM'}
          </h1>
          <p className="text-sm text-muted-foreground">
            {rmInfo?.email} • View all unlisted stock referred orders generated by this Relationship Manager.
          </p>
        </div>
        <Badge className="bg-emerald-100 text-emerald-800 border-none font-semibold text-xs py-1 px-3">
          Relationship Manager Sales
        </Badge>
      </div>

      {/* KPI Stats cards */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-6">
        <Card className="shadow-sm border-muted/50">
          <CardContent className="p-5 flex items-center justify-between">
            <div className="space-y-1">
              <p className="text-xs font-semibold text-muted-foreground uppercase tracking-wider">Total Conversions</p>
              <h3 className="text-2xl font-bold tracking-tight mt-1">{totalConversions} sales</h3>
            </div>
            <div className="p-3 bg-primary/10 text-primary rounded-lg">
              <Users className="h-5 w-5" />
            </div>
          </CardContent>
        </Card>

        <Card className="shadow-sm border-muted/50">
          <CardContent className="p-5 flex items-center justify-between">
            <div className="space-y-1">
              <p className="text-xs font-semibold text-muted-foreground uppercase tracking-wider">Revenue Driven</p>
              <h3 className="text-2xl font-bold tracking-tight text-emerald-600 mt-1">
                ₹{totalRevenueDriven.toLocaleString('en-IN', { maximumFractionDigits: 2 })}
              </h3>
            </div>
            <div className="p-3 bg-emerald-500/10 text-emerald-600 rounded-lg">
              <DollarSign className="h-5 w-5" />
            </div>
          </CardContent>
        </Card>

        <Card className="shadow-sm border-muted/50">
          <CardContent className="p-5 flex items-center justify-between">
            <div className="space-y-1">
              <p className="text-xs font-semibold text-muted-foreground uppercase tracking-wider">Discounts Disbursed</p>
              <h3 className="text-2xl font-bold tracking-tight text-amber-600 mt-1">
                -₹{totalDiscountDisbursed.toLocaleString('en-IN', { maximumFractionDigits: 2 })}
              </h3>
            </div>
            <div className="p-3 bg-amber-500/10 text-amber-600 rounded-lg">
              <BarChart3 className="h-5 w-5" />
            </div>
          </CardContent>
        </Card>
      </div>

      {/* Premium Full-Width Search Input */}
      <div className="relative w-full shadow-sm rounded-lg overflow-hidden border bg-background flex items-center px-4 h-12">
        <Search className="h-5 w-5 text-muted-foreground shrink-0 mr-3" />
        <input
          type="text"
          placeholder="Search referred logs by client name, email, stock, or referral code..."
          value={salesSearchQuery}
          onChange={(e) => setSalesSearchQuery(e.target.value)}
          className="w-full bg-transparent focus:outline-none text-sm text-foreground placeholder-muted-foreground font-medium"
        />
      </div>

      {/* Referred Transaction Logs Table */}
      <div className="border rounded-md overflow-hidden bg-background shadow-sm">
        <div className="p-4 border-b bg-muted/20">
          <h2 className="text-sm font-semibold">RM Referral Transaction Logs</h2>
        </div>
        {sales.length === 0 ? (
          <div className="border border-dashed rounded-lg flex flex-col items-center justify-center p-12 text-center bg-muted/10">
            <Ticket className="h-10 w-10 text-muted-foreground mb-3" />
            <h3 className="text-base font-semibold mb-1">No sales recorded</h3>
            <p className="text-xs text-muted-foreground max-w-xs">
              This Relationship Manager has not recorded any unlisted stock referral sales yet.
            </p>
          </div>
        ) : filteredSales.length === 0 ? (
          <div className="border border-dashed rounded-lg flex flex-col items-center justify-center p-12 text-center bg-muted/10">
            <h3 className="text-base font-semibold mb-1">No matches found</h3>
            <p className="text-xs text-muted-foreground max-w-xs">
              Your search query did not match any sales records under this relationship manager.
            </p>
          </div>
        ) : (
          <div className="overflow-x-auto">
            <Table>
              <TableHeader className="bg-muted/30">
                <TableRow>
                  <TableHead>Code</TableHead>
                  <TableHead>Stock</TableHead>
                  <TableHead>Client Details</TableHead>
                  <TableHead className="text-center">Qty</TableHead>
                  <TableHead className="text-right">Discount</TableHead>
                  <TableHead className="text-right">Revenue</TableHead>
                  <TableHead className="text-right">Redeemed At</TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {filteredSales.map((sale) => (
                  <TableRow key={sale.id} className="hover:bg-muted/30 transition-colors">
                    <TableCell className="py-3">
                      <div className="flex items-center gap-1.5">
                        <code className="font-mono font-medium text-xs text-foreground bg-muted px-2 py-0.5 rounded">
                          {sale.code}
                        </code>
                        <Button
                          variant="ghost"
                          size="icon"
                          className="h-6 w-6 text-muted-foreground hover:text-foreground"
                          onClick={(e) => {
                            e.stopPropagation();
                            copyToClipboard(sale.code);
                          }}
                        >
                          {copiedCode === sale.code ? (
                            <CheckCircle2 className="h-3.5 w-3.5 text-emerald-500" />
                          ) : (
                            <Copy className="h-3 w-3" />
                          )}
                        </Button>
                      </div>
                    </TableCell>
                    <TableCell className="font-semibold py-3">{sale.stock?.name}</TableCell>
                    <TableCell className="py-3">
                      <div className="flex flex-col">
                        <span className="font-medium text-xs text-foreground">
                          {sale.usedByUser?.fullName || 'Client'}
                        </span>
                        <span className="text-[10px] text-muted-foreground mt-0.5">
                          {sale.usedByUser?.email || 'No email'}
                        </span>
                        {sale.usedByUser?.phone && (
                          <span className="text-[10px] text-muted-foreground mt-0.5">
                            📞 {sale.usedByUser.phone}
                          </span>
                        )}
                      </div>
                    </TableCell>
                    <TableCell className="text-center py-3">
                      {sale.order?.quantity ? (
                        <Badge variant="outline" className="text-xs bg-indigo-50/50 text-indigo-700 dark:bg-indigo-950/30 dark:text-indigo-400 border-indigo-100 font-semibold font-mono">
                          {sale.order.quantity}
                        </Badge>
                      ) : (
                        <span className="text-muted-foreground text-xs italic">-</span>
                      )}
                    </TableCell>
                    <TableCell className="text-right font-semibold text-emerald-600 dark:text-emerald-500 py-3">
                      {sale.discountType === 'PERCENTAGE' && sale.discountPercentage
                        ? `-${sale.discountPercentage}%`
                        : `-₹${sale.discountAmount.toLocaleString('en-IN', { maximumFractionDigits: 2 })}`}
                    </TableCell>
                    <TableCell className="text-right font-bold text-foreground py-3 font-mono text-xs">
                      {sale.order?.totalAmount ? (
                        `₹${sale.order.totalAmount.toLocaleString('en-IN', { minimumFractionDigits: 2 })}`
                      ) : (
                        <span className="text-muted-foreground font-normal text-xs italic">Pending</span>
                      )}
                    </TableCell>
                    <TableCell className="text-right py-3">
                      <div className="flex items-center justify-end gap-1 text-[11px] text-muted-foreground font-medium">
                        <Calendar className="h-3 w-3" />
                        <span>
                          {new Date(sale.usedAt || sale.createdAt).toLocaleDateString('en-IN', {
                            day: 'numeric',
                            month: 'short',
                            year: 'numeric',
                          })}
                        </span>
                      </div>
                    </TableCell>
                  </TableRow>
                ))}
              </TableBody>
            </Table>
          </div>
        )}
      </div>
    </div>
  );
}

export default function RmSalesPopupPage() {
  return (
    <Suspense
      fallback={
        <div className="flex h-screen items-center justify-center bg-background">
          <Loader2 className="h-8 w-8 animate-spin text-primary" />
        </div>
      }
    >
      <RmSalesPopupContent />
    </Suspense>
  );
}
